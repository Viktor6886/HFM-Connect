#!/usr/bin/env python3
"""Bundle webui/ (index.html + app.css + app.js) into one gzip'ed HTML page and
emit firmware/HFMConnect/WebUiAssets.h (PROGMEM byte arrays).

The reference catalogue (data/reference/hfm_reference.json + DTC catalogue status and
variant-map membership from data/protocol/) is embedded as a second gzip'ed asset
served at /ref.json; its version is injected into app.js (__REF_VERSION__).

    python tools/build_webui.py          # rebuild header
    python tools/build_webui.py --check  # CI: fail if header is stale
"""
import csv
import gzip
import hashlib
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
WEB = ROOT / "webui"
DST = ROOT / "firmware" / "HFMConnect" / "WebUiAssets.h"


def reference() -> bytes:
    ref = json.loads((ROOT / "data" / "reference" / "hfm_reference.json").read_text(encoding="utf-8"))
    vm = json.loads((ROOT / "data" / "protocol" / "dtc_variant_maps.json").read_text(encoding="utf-8"))["maps"]
    rows = {int(r["code"]): r for r in csv.DictReader((ROOT / "data" / "protocol" / "dtc.csv").open(encoding="utf-8-sig"))}
    ref["maps"] = {k: {"cyl": m["cylinders"], "vendor": m["vendor"], "diag": m["diag"]} for k, m in vm.items()}
    for code, x in ref["dtc"].items():
        c = int(code)
        x["maps"] = [k for k, m in vm.items() if c in m["positions"]]
        r = rows.get(c)
        x["cs"] = r["catalog_status"] if r else ""
        x["en"] = r["description_en"] if r else ""
    return json.dumps(ref, ensure_ascii=False, separators=(",", ":")).encode("utf-8")


def bundle(ref_version: str) -> bytes:
    html = (WEB / "index.html").read_text(encoding="utf-8")
    css = (WEB / "app.css").read_text(encoding="utf-8")
    js = (WEB / "app.js").read_text(encoding="utf-8").replace("__REF_VERSION__", ref_version)
    html = html.replace('<link rel="stylesheet" href="app.css">', "<style>\n" + css + "\n</style>")
    html = html.replace('<script src="app.js"></script>', "<script>\n" + js + "\n</script>")
    return html.encode("utf-8")


def c_array(name: str, data: bytes) -> list:
    lines = [f"static const size_t {name}_LEN = {len(data)};", f"static const uint8_t {name}[] PROGMEM = {{"]
    for i in range(0, len(data), 20):
        lines.append("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 20]) + ",")
    return lines + ["};", ""]


def render(page: bytes, ref: bytes) -> str:
    gz = gzip.compress(page, compresslevel=9, mtime=0)
    rgz = gzip.compress(ref, compresslevel=9, mtime=0)
    digest = hashlib.sha256(page).hexdigest()[:16]
    lines = [
        "// AUTO-GENERATED by tools/build_webui.py from webui/. Do not edit.",
        f"// source sha256/16: {digest}  raw: {len(page)} B",
        f"// gzip: {len(gz)} B (zlib level 9); reference /ref.json: raw {len(ref)} B, gzip {len(rgz)} B",
        "#pragma once",
        "#include <Arduino.h>",
        "",
    ]
    lines += c_array("WEBUI_INDEX_GZ", gz) + c_array("WEBUI_REF_GZ", rgz)
    return "\n".join(lines)


def main() -> int:
    ref = reference()
    page = bundle(hashlib.sha256(ref).hexdigest()[:12])
    text = render(page, ref)
    if "--check" in sys.argv:
        cur = DST.read_text(encoding="utf-8") if DST.exists() else ""
        if cur.splitlines()[:2] != text.splitlines()[:2]:
            print("WebUiAssets.h is stale: run python tools/build_webui.py")
            return 1
        print("WebUiAssets.h up to date")
        return 0
    DST.write_text(text, encoding="utf-8", newline="\n")
    (ROOT / "build").mkdir(exist_ok=True)
    (ROOT / "build" / "webui_bundle.html").write_bytes(page)
    print(f"wrote {DST.relative_to(ROOT)}: raw {len(page)} B")
    return 0


if __name__ == "__main__":
    sys.exit(main())
