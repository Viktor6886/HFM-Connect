def generate(kit):
    base=kit/'02_DATA/modules/HFM';signals={(f['screen'],f['output_word']):f for f in read(base,'signals')['fields']}
    out={}
    for s in read(base,'live_fields')['screens']:
        if not s['conversion']:continue
        i=s['screen']; fields=[]
        for f in s['fields']:
            n=f['output_word'];sig=signals[i,n];unit=sig['unit']; label=''
            if n<len(MULTI.get(i,[])):label=MULTI[i][n]
            elif i in (65,66,84,85):label=f'Цилиндр {n+1}'
            elif i in (72,76,80):label=['Цилиндры 2/5','Цилиндры 3/4','Цилиндры 1/6'][n]
            elif i in (73,77,81,146):label=['Цилиндры 1/4','Цилиндры 2/3'][n]
            elif len(s['fields'])>1:label=f'Значение {n+1}'
            choices=[[v['mask'],CHOICES.get(v['text'],v['text'])] for v in f.get('bit_choices',{}).get('en',[])]
            fields.append([n,label,UNITS.get(unit,unit) or '',f['decimal_places'],f.get('signed',True),choices])
        out[i]=[TITLES[i],fields]
    assert len(out)==112 and sum(len(v[1]) for v in out.values())==163
    test=read(base,'special_tests')['tests'][0]
    for cylinders in (4,6):
        screen=test['read_screens'][f'{cylinders}_cylinders']
        out[screen]=[f'Равномерность работы, {cylinders} цилиндра' if cylinders==4 else 'Равномерность работы, 6 цилиндров',
                     [[i,f'Цилиндр {i+1}','об/мин',0,False,[]] for i in range(cylinders)]]
    return 'const HHT_SCREENS = '+json.dumps(out,ensure_ascii=False,separators=(',',':'))+';\n'
if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('kit',type=Path);ap.add_argument('--check',action='store_true')
    a=ap.parse_args();data=generate(a.kit);out=ROOT/'webui/hht-screens.js'
    if a.check:
        if out.read_text(encoding='utf8')!=data:raise SystemExit('screen labels differ')
    else:out.write_text(data,encoding='utf8')
