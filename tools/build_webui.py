#!/usr/bin/env python3
"""Bundle webui/ (index.html + app.css + app.js) into one gzip'ed HTML page and
emit firmware/HFMConnect/WebUiAssets.h (PROGMEM byte array).

    python tools/build_webui.py          # rebuild header
    python tools/build_webui.py --check  # CI: fail if header is stale
"""
import gzip
import hashlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
WEB = ROOT / "webui"
DST = ROOT / "firmware" / "HFMConnect" / "WebUiAssets.h"


def bundle() -> bytes:
    html = (WEB / "index.html").read_text(encoding="utf-8")
    css = (WEB / "app.css").read_text(encoding="utf-8")
    js = (WEB / "app.js").read_text(encoding="utf-8")
    html = html.replace('<link rel="stylesheet" href="app.css">', "<style>\n" + css + "\n</style>")
    html = html.replace('<script src="app.js"></script>', "<script>\n" + js + "\n</script>")
    return html.encode("utf-8")


def render(page: bytes) -> str:
    gz = gzip.compress(page, compresslevel=9, mtime=0)
    digest = hashlib.sha256(page).hexdigest()[:16]
    lines = [
        "// AUTO-GENERATED by tools/build_webui.py from webui/. Do not edit.",
        f"// source sha256/16: {digest}  raw: {len(page)} B",
        f"// gzip: {len(gz)} B (zlib level 9)",
        "#pragma once",
        "#include <Arduino.h>",
        "",
        f"static const size_t WEBUI_INDEX_GZ_LEN = {len(gz)};",
        "static const uint8_t WEBUI_INDEX_GZ[] PROGMEM = {",
    ]
    for i in range(0, len(gz), 20):
        lines.append("  " + ",".join(f"0x{b:02x}" for b in gz[i:i + 20]) + ",")
    lines += ["};", ""]
    return "\n".join(lines)


def main() -> int:
    page = bundle()
    text = render(page)
    if "--check" in sys.argv:
        cur = DST.read_text(encoding="utf-8") if DST.exists() else ""
        if cur.splitlines()[:2] != text.splitlines()[:2]:
            print("WebUiAssets.h is stale: run python tools/build_webui.py")
            return 1
        print("WebUiAssets.h up to date")
        return 0
    DST.write_text(text, encoding="utf-8", newline="\n")
    (ROOT / "build").mkdir(exist_ok=True)
    (ROOT / "build" / "webui_bundle.html").write_bytes(page)
    print(f"wrote {DST.relative_to(ROOT)}: raw {len(page)} B")
    return 0


if __name__ == "__main__":
    sys.exit(main())
