#!/usr/bin/env python3
"""Generate firmware/HFMConnect/DtcCatalog.h from data/hfmreader/dtc.csv.

The CSV is the HFMreader 1.1.1 catalog (163 entries) recovered in the project
analysis (see docs/PROTOCOL.md, source S-HR). Run after editing the CSV:

    python tools/gen_dtc_catalog.py
"""
import csv
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "data" / "hfmreader" / "dtc.csv"
DST = ROOT / "firmware" / "HFMConnect" / "DtcCatalog.h"

STATUS = {
    "oem_supported": "DTC_SRC_OEM",
    "reference_supported": "DTC_SRC_REFERENCE",
    "reconciliation_required": "DTC_SRC_RECONCILE",
    "unverified": "DTC_SRC_UNVERIFIED",
    "application_label": "DTC_SRC_APP_LABEL",
}


def c_str(s: str) -> str:
    s = s.replace("\\", "\\\\").replace('"', '\\"').strip()
    return '"' + s + '"'


def main() -> int:
    rows = list(csv.DictReader(SRC.open(encoding="utf-8-sig")))
    rows.sort(key=lambda r: int(r["code"]))
    out = [
        "// AUTO-GENERATED by tools/gen_dtc_catalog.py from data/hfmreader/dtc.csv. Do not edit.",
        "// Source: HFMreader 1.1.1 dtc_catalog.json (163 entries), analyst RU translation.",
        "// Catalog meaning is NOT bit-position proof: see docs/PROTOCOL.md section DTC.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "enum DtcSource : uint8_t { DTC_SRC_OEM, DTC_SRC_REFERENCE, DTC_SRC_RECONCILE, DTC_SRC_UNVERIFIED, DTC_SRC_APP_LABEL };",
        "enum DtcFlags : uint8_t { DTC_F_NONE = 0, DTC_F_INTERMITTENT = 1, DTC_F_NOT_W124 = 2 };",
        "",
        "struct DtcCatalogEntry {",
        "  uint16_t code;",
        "  uint8_t source;  // DtcSource",
        "  uint8_t flags;   // DtcFlags",
        "  const char* ru;",
        "  const char* en;",
        "};",
        "",
        "static const DtcCatalogEntry DTC_CATALOG[] = {",
    ]
    for r in rows:
        en = r["description_en"]
        flags = []
        if "intermittent" in en.lower():
            flags.append("DTC_F_INTERMITTENT")
        if "excludes model 124" in r.get("applicability_note", "").lower():
            flags.append("DTC_F_NOT_W124")
        fl = "|".join(flags) if flags else "DTC_F_NONE"
        if len(flags) > 1:
            fl = f"(uint8_t)({fl})"
        out.append(
            f"  {{{int(r['code'])}, {STATUS[r['catalog_status']]}, {fl}, "
            f"{c_str(r['description_ru (translation by analyst)'])}, {c_str(en)}}},"
        )
    out += [
        "};",
        f"static const uint16_t DTC_CATALOG_COUNT = {len(rows)};",
        "",
    ]
    DST.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {DST.relative_to(ROOT)} ({len(rows)} entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
