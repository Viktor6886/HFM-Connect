#!/usr/bin/env python3
"""Generate firmware/HFMConnect/DtcCatalog.h from data/protocol/dtc.csv.

The CSV is the project DTC catalog (163 entries, EN text + RU translation,
see docs/PROTOCOL.md). Run after editing the CSV:

    python tools/gen_dtc_catalog.py
"""
import csv
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "data" / "protocol" / "dtc.csv"
DST = ROOT / "firmware" / "HFMConnect" / "DtcCatalog.h"

STATUS = {
    "oem_supported": "DTC_SRC_OEM",
    "reference_supported": "DTC_SRC_REFERENCE",
    "reconciliation_required": "DTC_SRC_RECONCILE",
    "unverified": "DTC_SRC_UNVERIFIED",
    "application_label": "DTC_SRC_APP_LABEL",
    "hht_candidate": "DTC_SRC_CANDIDATE",  # text from factory tester context rules, not ECU-verified
}


def c_str(s: str) -> str:
    s = s.replace("\\", "\\\\").replace('"', '\\"').strip()
    return '"' + s + '"'


def write_variant_maps():
    import json
    src = json.loads((ROOT / "data" / "protocol" / "dtc_variant_maps.json").read_text(encoding="utf-8"))
    dst = ROOT / "firmware" / "HFMConnect" / "DtcVariantMaps.h"
    diag = {"lt_I": "DIAG_LT_I", "I_to_P": "DIAG_I_TO_P", "ge_I": "DIAG_GE_I", "ge_P": "DIAG_GE_P"}
    out = [
        "// AUTO-GENERATED by tools/gen_dtc_catalog.py from data/protocol/dtc_variant_maps.json. Do not edit.",
        "// Factory tester DTC bit maps (REV 1.1 s.12): position 1..152 -> code, 0 = not used.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "enum DtcDiagRange : uint8_t { DIAG_LT_I, DIAG_I_TO_P, DIAG_GE_I, DIAG_GE_P };",
        "",
        "struct DtcVariantMap {",
        "  const char* id;",
        "  uint8_t cylinders;   // 4 / 6",
        "  const char* vendors; // \"B\", \"V\" or \"VB\"",
        "  uint8_t diag;        // DtcDiagRange",
        "  uint16_t pos[152];",
        "};",
        "",
        "static const DtcVariantMap DTC_VARIANT_MAPS[] = {",
    ]
    for mid, m in src["maps"].items():
        vals = ", ".join(str(v) for v in m["positions"])
        out.append(f'  {{"{mid}", {m["cylinders"]}, "{m["vendor"]}", {diag[m["diag"]]}, {{{vals}}}}},')
    out += ["};", f"static const uint8_t DTC_VARIANT_MAP_COUNT = {len(src['maps'])};", ""]
    dst.write_text(chr(10).join(out), encoding="utf-8", newline=chr(10))
    print(f"wrote {dst.relative_to(ROOT)} ({len(src['maps'])} maps)")


def main() -> int:
    rows = list(csv.DictReader(SRC.open(encoding="utf-8-sig")))
    rows.sort(key=lambda r: int(r["code"]))
    out = [
        "// AUTO-GENERATED by tools/gen_dtc_catalog.py from data/protocol/dtc.csv. Do not edit.",
        "// Project DTC catalog (163 entries): factory meanings where available, RU translation.",
        "// Catalog meaning is NOT bit-position proof: see docs/PROTOCOL.md section DTC.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "enum DtcSource : uint8_t { DTC_SRC_OEM, DTC_SRC_REFERENCE, DTC_SRC_RECONCILE, DTC_SRC_UNVERIFIED, DTC_SRC_APP_LABEL,",
        "                           DTC_SRC_CANDIDATE };",
        "enum DtcFlags : uint8_t { DTC_F_NONE = 0, DTC_F_INTERMITTENT = 1, DTC_F_NOT_W124 = 2 };",
        "",
        "struct DtcCatalogEntry {",
        "  uint16_t code;",
        "  uint8_t source;  // DtcSource",
        "  uint8_t flags;   // DtcFlags",
        "  const char* ru;",
        "  const char* en;",
        "};",
        "",
        "static const DtcCatalogEntry DTC_CATALOG[] = {",
    ]
    for r in rows:
        en = r["description_en"]
        flags = []
        if "intermittent" in en.lower():
            flags.append("DTC_F_INTERMITTENT")
        if "excludes model 124" in r.get("applicability_note", "").lower():
            flags.append("DTC_F_NOT_W124")
        fl = "|".join(flags) if flags else "DTC_F_NONE"
        if len(flags) > 1:
            fl = f"(uint8_t)({fl})"
        out.append(
            f"  {{{int(r['code'])}, {STATUS[r['catalog_status']]}, {fl}, "
            f"{c_str(r['description_ru'])}, {c_str(en)}}},"
        )
    out += [
        "};",
        f"static const uint16_t DTC_CATALOG_COUNT = {len(rows)};",
        "",
    ]
    DST.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {DST.relative_to(ROOT)} ({len(rows)} entries)")
    write_variant_maps()
    return 0


if __name__ == "__main__":
    sys.exit(main())
